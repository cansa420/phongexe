const F = {
  0: '111101101101111', 1: '010110010010111', 2: '111001111100111', 3: '111001111001111', 4: '101101111001001', 5: '111100111001111', 6: '111100111101111', 7: '111001001001001', 8: '111101111101111', 9: '111101111001111',
  x: '000101010101000', '+': '000010111010000', '.': '000000000000010',
};
function text(img, s, x, y, c) { for (const ch of s) { const bm = F[ch]; if (!bm) continue; for (let i = 0; i < 15; i++) if (bm[i] === '1') img.set(x + (i % 3), y + Math.floor(i / 3), c); x += ch === '.' ? 2 : 4; } }
const textW = (s) => [...s].reduce((w, ch) => w + (ch === '.' ? 2 : 4), 0) - 1;

function icon(c) {
  const [glyph, label] = MAP[c.id]; const g = new Img(32, 32);
  const bm = G[glyph]; const col = BUILD_COL[c.build]; const dark = mix(col, P.den, 0.5);
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) if (bm[y][x] === '#') { g.rect(4 + x * 3 + 1, 2 + y * 3 + 1, 3, 3, dark); }
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) if (bm[y][x] === '#') { g.rect(4 + x * 3, 2 + y * 3, 3, 3, col); }
  if (label) { const w = textW(label); const bx = 31 - w - 3; g.rect(bx, 24, w + 3, 8, P.den); text(g, label, bx + 1, 25, P.kem); }
  return g;
}

module.exports = function genCharms(outDir) {
  let n = 0;
  for (const c of CHARMS) { if (!MAP[c.id]) throw new Error('thiếu icon cho ' + c.id); icon(c).save(`${outDir}/charms/${c.id}.png`); n++; }
  return n;
};
